FA_DIGITS = str.maketrans('0123456789.,', '۰۱۲۳۴۵۶۷۸۹٫٬')


def fa(s):
    return str(s).translate(FA_DIGITS)


def esc(s):
    return str(s).replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def t(x, y, s, size=13, fill=INK, anchor='end', weight='400', op=1.0, ls=0):
    return ('<text x="%.1f" y="%.1f" font-size="%.1f" fill="%s" text-anchor="%s" font-weight="%s" '
            'font-family="%s" opacity="%.2f" letter-spacing="%.2f">%s</text>'
            % (x, y, size, fill, anchor, weight, FF, op, ls, esc(s)))


def wrap(text, width, size, factor=0.5):
    maxc = max(8, int(width / (factor * size)))
    words = text.split(' ')
    lines, cur = [], ''
    for w in words:
        cand = (cur + ' ' + w).strip()
        if len(cand) > maxc and cur:
            lines.append(cur)
            cur = w
        else:
            cur = cand
    if cur:
        lines.append(cur)
    return lines


def para(x, y, text, width, size=13, lh=1.85, fill=INK):
    out, yy = [], y
    for ln in wrap(text, width, size):
        out.append(t(x, yy, ln, size=size, fill=fill))
        yy += size * lh
    return ''.join(out), yy


def bullets(x, y, items, width, size=13, lh=1.85, gap=9, color=ACC):
    out, yy = [], y
    for it in items:
        out.append('<circle cx="%.1f" cy="%.1f" r="2.6" fill="%s"/>' % (x - 6, yy - 4.2, color))
        body, yy2 = para(x - 18, yy, it, width - 18, size=size, lh=lh)
        out.append(body)
        yy = yy2 + gap
    return ''.join(out), yy


