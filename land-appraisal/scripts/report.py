def table(y, cols, rows, rowh=32, size=11, headsize=10.8, zebra=True):
    total_w = sum(c['w'] for c in cols)
    x0 = W - M
    o = ['<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#eef3f5"/>'
         % (x0 - total_w, y, total_w, rowh)]
    x = x0
    for c in cols:
        o.append(t(x - c['w'] / 2, y + rowh / 2 + 4, c['label'], size=headsize,
                   fill=ACC, weight='700', anchor='middle'))
        x -= c['w']
    o.append('<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="%s" stroke-width="1.1"/>'
             % (x0 - total_w, y + rowh, x0, y + rowh, ACC))
    yy = y + rowh
    for i, r in enumerate(rows):
        if zebra and i % 2 == 1:
            o.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="#fafbfc"/>'
                     % (x0 - total_w, yy, total_w, rowh))
        x = x0
        for j, c in enumerate(cols):
            v = r[j]
            if c.get('fa', False):
                v = fa(v)
            o.append(t(x - c['w'] / 2, yy + rowh / 2 + 4, v, size=size,
                       fill=c.get('color', INK), anchor='middle',
                       weight=('700' if j == 0 else '400')))
            x -= c['w']
        o.append('<line x1="%.1f" y1="%.1f" x2="%.1f" y2="%.1f" stroke="#e9edf1"/>'
                 % (x0 - total_w, yy + rowh, x0, yy + rowh))
        yy += rowh
    return ''.join(o), yy


def kpi(x, y, w, h, value, label, color=ACC):
    o = ['<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" rx="6" fill="#fff" stroke="%s"/>'
         % (x, y, w, h, LINE)]
    o.append('<rect x="%.1f" y="%.1f" width="4" height="%.1f" rx="2" fill="%s"/>'
             % (x + w - 4, y + 10, h - 20, color))
    o.append(t(x + w - 18, y + h / 2 + 2, value, size=19, weight='700', fill=color))
    o.append(t(x + w - 18, y + h / 2 + 22, label, size=10.2, fill=MUT))
    return ''.join(o)


def svgpage(body):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">%s</svg>'
            % (W, H, W, H, body))


def render(svg, name, scale=2):
    p = os.path.join(TMP, name + '.svg')
    open(p, 'w').write(svg)
    png = os.path.join(TMP, name + '.png')
    subprocess.run(['node', '/home/user/tools/svgrender/render.js', p, png, str(W * scale)],
                   check=True, stdout=subprocess.DEVNULL)
    return png


